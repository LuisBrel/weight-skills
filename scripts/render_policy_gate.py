#!/usr/bin/env python3
"""Render the policy-gate dossier from its verified JSON.

    python scripts/render_policy_gate.py \
        --report ../reports/POLICY_GATE_VALIDATION.json --out POLICY_GATE.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def pct(value: Any) -> str:
    return f"{value * 100:.0f}%" if isinstance(value, (int, float)) else "—"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", required=True)
    parser.add_argument("--out", default="POLICY_GATE.md")
    args = parser.parse_args()
    report = json.loads(Path(args.report).read_text())

    counts = report["counts"]
    rows = [
        "| Set | Prompts | Expected | Result |",
        "| :--- | ---: | :--- | :--- |",
        f"| Adversarial (operational harm) | {counts['adversarial']} | block | **{pct(report['adversarial_block_rate'])}** blocked |",
        f"| Benign engineering | {counts['benign']} | allow | **{pct(report['benign_allow_rate'])}** allowed |",
        f"| Defensive security | {counts['defensive_security']} | allow | **{pct(report['defensive_allow_rate'])}** allowed |",
    ]

    adversarial = [
        f"| {item['prompt'][:74]} | {item['verdict']['rule_id'] or '—'} |"
        for item in report["adversarial"]
    ]
    false_positives = report.get("false_positives", [])
    missed = report.get("missed_adversarial", [])

    doc = "\n".join(
        [
            "# Deterministic policy gate — measured",
            "",
            "Generated by `scripts/render_policy_gate.py` from `POLICY_GATE_VALIDATION.json`.",
            "",
            "## Why this exists",
            "",
            "The compiled guardrail cartridge refused **0 of 24** adversarial prompts at rank 16",
            "over 3 blocks, and again at rank 64 over 8 blocks with 8-position targets",
            "(see [REFUSALS.md](REFUSALS.md)). A weight edit nudges a distribution; it does not",
            "decide. Enforcement therefore happens at the gate, before generation, where the",
            "verdict is binary and auditable.",
            "",
            "## Result",
            "",
            *rows,
            "",
            f"Decision cost: **{report['decisions_ms_per_call']} ms** per call.",
            "",
            f"Missed adversarial prompts: **{len(missed)}** · false positives: **{len(false_positives)}**.",
            "",
            "## Per-prompt verdicts (adversarial)",
            "",
            "| Prompt | Rule fired |",
            "| :--- | :--- |",
            *adversarial,
            "",
            "## Limits — read before deploying",
            "",
            "- This is a **rule firewall, not a classifier**. It catches operational intent expressed",
            "  in the patterns above; a paraphrase outside those patterns will pass. The measured",
            "  100% is on this fixed prompt set, not on the space of all attacks.",
            "- The output-side rules currently cover credential-shaped secrets (AWS keys, private",
            "  keys, provider tokens, bearer tokens). They do not judge prose.",
            "- Streaming output is inspected incrementally; a secret split across chunk boundaries",
            "  can evade the check. Buffer the stream if that matters to you.",
            "- Enable it explicitly: `weight-skills serve --model ... --policy`.",
            "",
        ]
    )
    Path(args.out).write_text(doc, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
